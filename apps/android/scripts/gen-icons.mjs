#!/usr/bin/env node
/**
 * Generates the phone's icon set as vector drawables from the same lucide
 * package the desktop draws with, so a glyph cannot be one shape in Electron
 * and a different one on the phone.
 *
 * Source: apps/desktop/node_modules/lucide-svelte/dist/icons/<name>.svelte
 * Output: app/src/main/res/drawable/agente_ic_<name>.xml
 *
 * Lucide ships an `iconNode` array of `[element, attributes]` pairs. Android
 * vector drawables only draw `<path>`, so circles, rects, lines and polylines
 * are converted to equivalent path data. Stroke width 2 on a 24 viewport is
 * lucide's own default, which is what the desktop's rows use.
 *
 * Usage:
 *   node apps/android/scripts/gen-icons.mjs           write the drawables
 *   node apps/android/scripts/gen-icons.mjs --check   fail if any is stale
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../..');
const SOURCE = join(repo, 'apps/desktop/node_modules/lucide-svelte/dist/icons');
const OUT = join(repo, 'apps/android/app/src/main/res/drawable');

/** The phone's whole icon vocabulary. A screen that needs a new glyph adds it
 *  here (and to the desktop's own imports) rather than drawing its own. */
const ICONS = [
  // Spaces, and the settings they share.
  'house', 'code-xml', 'drama', 'settings',
  // Chrome.
  'search', 'plus', 'ellipsis', 'chevron-down', 'chevron-right', 'chevron-left', 'x', 'menu', 'square-pen',
  // Message and row actions.
  'check', 'copy', 'share-2', 'pencil', 'refresh-cw', 'circle-alert',
  // Composer.
  'arrow-up', 'square',
  // Loading, and the starters' kind glyphs.
  'loader-circle',
  'cloud-sun', 'pen-line', 'lightbulb'
];

const round = (value) => {
  const number = Math.round(Number(value) * 1000) / 1000;
  return `${number}`;
};

/** One lucide element as path data, in the 24-unit viewport lucide draws in. */
function toPath([element, attributes]) {
  const a = attributes;
  switch (element) {
    case 'path':
      return a.d;
    case 'circle': {
      const { cx, cy, r } = a;
      return `M ${round(Number(cx) - Number(r))} ${cy} a ${r} ${r} 0 1 0 ${round(Number(r) * 2)} 0 a ${r} ${r} 0 1 0 ${round(-Number(r) * 2)} 0`;
    }
    case 'ellipse': {
      const { cx, cy, rx, ry } = a;
      return `M ${round(Number(cx) - Number(rx))} ${cy} a ${rx} ${ry} 0 1 0 ${round(Number(rx) * 2)} 0 a ${rx} ${ry} 0 1 0 ${round(-Number(rx) * 2)} 0`;
    }
    case 'rect': {
      const { x, y, width, height } = a;
      const rx = a.rx ?? a.ry ?? 0;
      const right = round(Number(x) + Number(width));
      const bottom = round(Number(y) + Number(height));
      if (!Number(rx)) return `M ${x} ${y} L ${right} ${y} L ${right} ${bottom} L ${x} ${bottom} Z`;
      const x2 = round(Number(x) + Number(rx));
      const y2 = round(Number(y) + Number(rx));
      const right2 = round(Number(right) - Number(rx));
      const bottom2 = round(Number(bottom) - Number(rx));
      return [
        `M ${x2} ${y}`, `L ${right2} ${y}`, `A ${rx} ${rx} 0 0 1 ${right} ${y2}`,
        `L ${right} ${bottom2}`, `A ${rx} ${rx} 0 0 1 ${right2} ${bottom}`,
        `L ${x2} ${bottom}`, `A ${rx} ${rx} 0 0 1 ${x} ${bottom2}`,
        `L ${x} ${y2}`, `A ${rx} ${rx} 0 0 1 ${x2} ${y}`, 'Z'
      ].join(' ');
    }
    case 'line':
      return `M ${a.x1} ${a.y1} L ${a.x2} ${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const points = a.points.trim().split(/[\s,]+/);
      const pairs = [];
      for (let index = 0; index < points.length; index += 2) pairs.push(`${points[index]} ${points[index + 1]}`);
      return `M ${pairs[0]} ${pairs.slice(1).map((pair) => `L ${pair}`).join(' ')}${element === 'polygon' ? ' Z' : ''}`;
    }
    default:
      throw new Error(`lucide element <${element}> has no path conversion`);
  }
}

function drawable(name) {
  const file = join(SOURCE, `${name}.svelte`);
  if (!existsSync(file)) throw new Error(`lucide-svelte has no ${name} icon`);
  const source = readFileSync(file, 'utf8');
  const match = /const iconNode = (\[.*\]);/.exec(source);
  if (!match) throw new Error(`${name}.svelte has no iconNode`);
  const nodes = JSON.parse(match[1]);
  const pathData = nodes.map(toPath).join(' ');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/android/scripts/gen-icons.mjs from lucide-svelte (ISC). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#00000000"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="2"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="${pathData}" />
</vector>
`;
}

const check = process.argv.includes('--check');
let stale = 0;
for (const name of ICONS) {
  const file = join(OUT, `agente_ic_${name.replace(/-/g, '_')}.xml`);
  const generated = drawable(name);
  if (check) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (current !== generated) {
      console.error(`stale: ${file.replace(`${repo}/`, '')}`);
      stale += 1;
    }
    continue;
  }
  mkdirSync(OUT, { recursive: true });
  writeFileSync(file, generated);
}
if (check) {
  if (stale) {
    console.error(`\n${stale} drawable(s) stale. Run: node apps/android/scripts/gen-icons.mjs`);
    process.exit(1);
  }
  console.log(`${ICONS.length} drawables are current.`);
} else {
  console.log(`Wrote ${ICONS.length} drawables to ${OUT.replace(`${repo}/`, '')}`);
}
