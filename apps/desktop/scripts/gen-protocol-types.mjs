#!/usr/bin/env node
// Generates shared/agente-protocol.gen.ts from shared/agente-protocol.schema.json,
// the JSON Schema the Rust runtime publishes (crates/agente-protocol,
// `protocol_schema()`). Covers the schema shapes schemars emits for the
// protocol: objects, string enums, internally tagged unions, Option<T>,
// arrays and `$ref`s.
//
//   npm run gen:protocol           write the file
//   npm run gen:protocol -- --check  fail when it is out of date (CI)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = path.join(root, 'shared', 'agente-protocol.schema.json');
const outPath = path.join(root, 'shared', 'agente-protocol.gen.ts');

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
const definitions = schema.definitions ?? {};

function doc(text, indent) {
  if (!text) return '';
  const lines = String(text).split('\n');
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  const body = lines.map((line) => `${indent} * ${line}`.trimEnd()).join('\n');
  return `${indent}/**\n${body}\n${indent} */\n`;
}

function refName(ref) {
  const name = ref.replace('#/definitions/', '');
  if (!definitions[name]) throw new Error(`Unknown $ref ${ref}`);
  return name;
}

const union = (parts) => [...new Set(parts)].join(' | ');
/** Parenthesize unions used as array elements. */
const wrap = (text) => (text.includes(' | ') ? `(${text})` : text);

const PRIMITIVES = {
  string: () => 'string',
  integer: () => 'number',
  number: () => 'number',
  boolean: () => 'boolean',
  null: () => 'null',
  array: (node) => `${wrap(typeOf(node.items ?? true))}[]`,
  object: (node) => (node.properties ? objectType(node, '') : 'Record<string, unknown>')
};

function primitive(type, node) {
  const render = PRIMITIVES[type];
  if (!render) throw new Error(`Unsupported type ${type}`);
  return render(node);
}

/** Schema node → TypeScript type, first matching shape wins. */
const SHAPES = [
  [(node) => node === true || node === undefined, () => 'unknown'],
  [(node) => node === false, () => 'never'],
  [(node) => node.$ref, (node) => refName(node.$ref)],
  [(node) => node.allOf?.length === 1, (node) => typeOf(node.allOf[0])],
  [(node) => node.anyOf ?? node.oneOf, (node) => union((node.anyOf ?? node.oneOf).map((item) => typeOf(item)))],
  [(node) => node.enum, (node) => union(node.enum.map((value) => JSON.stringify(value)))],
  [(node) => Array.isArray(node.type), (node) => union(node.type.map((type) => primitive(type, node)))],
  [(node) => node.type, (node) => primitive(node.type, node)]
];

function typeOf(node) {
  const shape = SHAPES.find(([matches]) => matches(node));
  return shape ? shape[1](node) : 'unknown';
}

function objectType(node, indent) {
  const required = new Set(node.required ?? []);
  const inner = `${indent}  `;
  const fields = Object.entries(node.properties ?? {}).map(([name, prop]) => {
    const optional = required.has(name) ? '' : '?';
    return `${doc(prop.description, inner)}${inner}${name}${optional}: ${typeOf(prop)};`;
  });
  return `{\n${fields.join('\n')}\n${indent}}`;
}

const isObject = (node) => node.type === 'object' && Boolean(node.properties);

function unionMember(member) {
  if (!isObject(member)) return `  | ${typeOf(member)}`;
  return `${doc(member.description, '  ')}  | ${objectType(member, '  ')}`;
}

function declaration(name, node) {
  const header = doc(node.description, '');
  const members = node.oneOf ?? node.anyOf;
  if (members) return `${header}export type ${name} =\n${members.map(unionMember).join('\n')};\n`;
  if (isObject(node)) return `${header}export interface ${name} ${objectType(node, '')}\n`;
  return `${header}export type ${name} = ${typeOf(node)};\n`;
}

const version = /v(\d+)/.exec(schema.description ?? '')?.[1] ?? '?';
const body = Object.keys(definitions)
  .sort()
  .map((name) => declaration(name, definitions[name]))
  .join('\n');

const output = `// Generated by scripts/gen-protocol-types.mjs from agente-protocol.schema.json
// (Agente runtime protocol v${version}). Do not edit: change the Rust types in
// crates/agente-protocol, refresh the schema, then run \`npm run gen:protocol\`.

export const AGENTE_PROTOCOL_VERSION = ${version === '?' ? 'null' : version};

${body}`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (current !== output) {
    console.error(`${path.relative(root, outPath)} is out of date: run npm run gen:protocol`);
    process.exit(1);
  }
  console.log('protocol types are up to date');
} else {
  fs.writeFileSync(outPath, output);
  console.log(`wrote ${path.relative(root, outPath)} (${Object.keys(definitions).length} types)`);
}
