function bufferToBytes(buffer: Buffer | Uint8Array | ArrayBuffer): number[] {
  return Array.from(buffer instanceof Buffer ? buffer : Buffer.from(buffer));
}

export async function generateDocx(data: Record<string, unknown>) {
  const docx = await import('docx') as any;
  const title = text(data.title, 'Document');
  const subtitle = text(data.subtitle);
  const author = text(data.author, 'Chatea');
  const date = text(data.date, new Date().toISOString().slice(0, 10));
  const sections = normalizeSections(data.sections);
  const children: any[] = [
    new docx.Paragraph({
      spacing: { after: 120 },
      children: [new docx.TextRun({ text: 'CHATEA LM WORK PRODUCT', bold: true, color: '64748B', size: 18 })]
    }),
    new docx.Paragraph({
      text: title,
      heading: docx.HeadingLevel.TITLE,
      spacing: { after: 220 }
    }),
    ...(subtitle ? [new docx.Paragraph({
      children: [new docx.TextRun({ text: subtitle, italics: true, color: '475569', size: 26 })],
      spacing: { after: 180 }
    })] : []),
    new docx.Paragraph({
      children: [new docx.TextRun({ text: `Generated by ${author} on ${date}`, color: '64748B', size: 18 })],
      spacing: { after: 360 }
    }),
  ];

  for (const section of sections) {
    const heading = section.title || section.heading;
    if (heading) {
      children.push(new docx.Paragraph({
        text: heading,
        heading: docx.HeadingLevel.HEADING_1,
        spacing: { before: 240, after: 120 }
      }));
    }
    if (section.content) {
      for (const paragraph of section.content.split(/\n{2,}/).map((part) => part.trim()).filter(Boolean)) {
        children.push(new docx.Paragraph({
          children: [new docx.TextRun({ text: paragraph, size: 22 })],
          spacing: { after: 120 }
        }));
      }
    }
    for (const bullet of section.bullets || []) {
      children.push(new docx.Paragraph({
        text: bullet,
        bullet: { level: 0 },
        spacing: { after: 80 }
      }));
    }
    if (section.citations?.length) {
      children.push(new docx.Paragraph({
        children: [new docx.TextRun({ text: `Sources: ${section.citations.join(', ')}`, italics: true, color: '64748B', size: 18 })],
        spacing: { after: 100 }
      }));
    }
  }

  const document = new docx.Document({
    creator: author,
    title,
    styles: {
      default: {
        document: { run: { font: 'Aptos', size: 22 }, paragraph: { spacing: { line: 276 } } }
      }
    },
    sections: [{
      properties: {
        page: { margin: { top: 1080, right: 900, bottom: 900, left: 900 } }
      },
      footers: {
        default: new docx.Footer({
          children: [new docx.Paragraph({
            alignment: docx.AlignmentType.RIGHT,
            children: [
              new docx.TextRun({ text: 'Chatea', color: '64748B', size: 16 }),
              new docx.TextRun({ text: '  |  Page ', color: '64748B', size: 16 }),
              docx.PageNumber.CURRENT
            ]
          })]
        })
      },
      children
    }]
  });
  const buffer = await docx.Packer.toBuffer(document);
  return {
    bytes: bufferToBytes(buffer),
    mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
  };
}

/** Excel sheet names must be unique and ≤ 31 chars. */
export function uniqueWorksheetName(raw: string, used: Set<string>): string {
  let base = text(raw, 'Sheet').slice(0, 31) || 'Sheet';
  // Excel forbids: \ / ? * [ ]
  base = base.replace(/[\\/?*[\]]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 31) || 'Sheet';
  let candidate = base;
  let n = 2;
  while (used.has(candidate.toLowerCase())) {
    const suffix = ` (${n++})`;
    candidate = (base.slice(0, Math.max(1, 31 - suffix.length)) + suffix).slice(0, 31);
  }
  used.add(candidate.toLowerCase());
  return candidate;
}

export async function generateXlsx(data: Record<string, unknown>) {
  const ExcelJS = (await import('exceljs')).default;
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Chatea';
  workbook.created = new Date();

  const sheets = Array.isArray(data.sheets) ? data.sheets as SheetInput[] : [];
  const normalizedSheets = sheets.length ? sheets : [{
    name: text(data.title, 'Sheet 1'),
    columns: Array.isArray(data.columns) ? data.columns as SheetInput['columns'] : undefined,
    rows: Array.isArray(data.rows) ? data.rows as SheetInput['rows'] : []
  }];

  const usedSheetNames = new Set<string>();
  for (const rawSheet of normalizedSheets) {
    const sheetName = uniqueWorksheetName(String(rawSheet.name || 'Sheet'), usedSheetNames);
    const worksheet = workbook.addWorksheet(sheetName);
    const rows = Array.isArray(rawSheet.rows) ? rawSheet.rows : [];
    let columns = Array.isArray(rawSheet.columns) ? rawSheet.columns : [];

    if (!columns.length) {
      const objectRow = rows.find((row) => row && typeof row === 'object' && !Array.isArray(row)) as Record<string, unknown> | undefined;
      if (objectRow) columns = Object.keys(objectRow);
    }

    if (columns.length) {
      worksheet.columns = columns.map((column) => {
        if (typeof column === 'string') {
          return { header: column, key: column, width: Math.max(12, Math.min(36, column.length + 4)) };
        }
        const header = text(column?.header || column?.key, 'Column');
        const key = text(column?.key || column?.header, header);
        return { header, key, width: Number(column?.width) || Math.max(12, Math.min(36, header.length + 4)) };
      });
      worksheet.getRow(1).font = { bold: true };
      worksheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEFF3F8' } };
      worksheet.getRow(1).height = 22;
      worksheet.views = [{ state: 'frozen', ySplit: 1 }];
      worksheet.autoFilter = {
        from: { row: 1, column: 1 },
        to: { row: Math.max(1, rows.length + 1), column: columns.length }
      };
    }

    for (const row of rows) {
      worksheet.addRow(row as any);
    }

    worksheet.eachRow((row) => {
      row.eachCell((cell) => {
        cell.alignment = { vertical: 'top', wrapText: true };
        cell.border = {
          top: { style: 'thin', color: { argb: 'FFD8DEE8' } },
          left: { style: 'thin', color: { argb: 'FFD8DEE8' } },
          bottom: { style: 'thin', color: { argb: 'FFD8DEE8' } },
          right: { style: 'thin', color: { argb: 'FFD8DEE8' } }
        };
      });
    });

    worksheet.columns?.forEach((column: any) => {
      let max = Number(column.width) || 12;
      column.eachCell?.({ includeEmpty: true }, (cell: any) => {
        max = Math.max(max, Math.min(48, String(cell.text || cell.value || '').length + 3));
      });
      column.width = max;
    });
  }

  const buffer = await workbook.xlsx.writeBuffer();
  return {
    bytes: bufferToBytes(buffer),
    mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
  };
}

function pdfSafe(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[^\x20-\x7E]/g, '')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function wrapPdfLine(value: string, maxChars: number): string[] {
  const words = value.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (next.length > maxChars && current) {
      lines.push(current);
      current = word;
    } else {
      current = next;
    }
  }
  if (current) lines.push(current);
  return lines.length ? lines : [''];
}

export async function generatePdf(data: Record<string, unknown>) {
  const html = text(data.html);
  if (html) {
    try {
      const { BrowserWindow } = await import('electron');
      const win = new BrowserWindow({
        show: false,
        width: 920,
        height: 1200,
        webPreferences: { sandbox: true, nodeIntegration: false, contextIsolation: true }
      });
      await win.loadURL(`data:text/html;charset=utf-8,${encodeURIComponent(html)}`);
      const buffer = await win.webContents.printToPDF({
        printBackground: true,
        margins: { marginType: 'default' },
        pageSize: 'A4'
      });
      win.destroy();
      return { bytes: bufferToBytes(buffer), mime: 'application/pdf' };
    } catch {
      // Fall through to the simple PDF writer if Chromium PDF rendering is unavailable.
    }
  }
  const title = text(data.title, 'Document');
  const sections = normalizeSections(data.sections);
  const pageHeight = 792;
  const margin = 72;
  const pageLines: Array<Array<{ text: string; size: number; bold?: boolean }>> = [[]];

  function pushLine(line: { text: string; size: number; bold?: boolean }) {
    const current = pageLines[pageLines.length - 1];
    if (current.length >= 42) pageLines.push([]);
    pageLines[pageLines.length - 1].push(line);
  }

  pushLine({ text: title, size: 22, bold: true });
  pushLine({ text: '', size: 12 });
  for (const section of sections) {
    const heading = section.title || section.heading;
    if (heading) {
      pushLine({ text: heading, size: 15, bold: true });
    }
    if (section.content) {
      for (const paragraph of section.content.split(/\n+/).map((part) => part.trim()).filter(Boolean)) {
        for (const line of wrapPdfLine(paragraph, 88)) pushLine({ text: line, size: 11 });
        pushLine({ text: '', size: 8 });
      }
    }
    for (const bullet of section.bullets || []) {
      for (const [index, line] of wrapPdfLine(bullet, 84).entries()) {
        pushLine({ text: `${index === 0 ? '- ' : '  '}${line}`, size: 11 });
      }
    }
    pushLine({ text: '', size: 8 });
  }

  const objects: string[] = [];
  const pageRefs: number[] = [];
  const fontRef = 3;
  objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  objects[3] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';

  for (let index = 0; index < pageLines.length; index += 1) {
    const pageRef = 4 + index * 2;
    const contentRef = pageRef + 1;
    pageRefs.push(pageRef);
    let y = pageHeight - margin;
    const ops: string[] = [];
    for (const line of pageLines[index]) {
      if (!line.text) {
        y -= Math.max(10, line.size);
        continue;
      }
      ops.push(`BT /F1 ${line.size} Tf ${margin} ${y} Td (${pdfSafe(line.text)}) Tj ET`);
      y -= Math.max(14, line.size + 4);
    }
    const stream = ops.join('\n');
    objects[pageRef] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 ${fontRef} 0 R >> >> /Contents ${contentRef} 0 R >>`;
    objects[contentRef] = `<< /Length ${Buffer.byteLength(stream, 'ascii')} >>\nstream\n${stream}\nendstream`;
  }

  objects[2] = `<< /Type /Pages /Kids [${pageRefs.map((ref) => `${ref} 0 R`).join(' ')}] /Count ${pageRefs.length} >>`;

  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  for (let i = 1; i < objects.length; i += 1) {
    offsets[i] = Buffer.byteLength(pdf, 'ascii');
    pdf += `${i} 0 obj\n${objects[i]}\nendobj\n`;
  }
  const xrefOffset = Buffer.byteLength(pdf, 'ascii');
  pdf += `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
  for (let i = 1; i < objects.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  return {
    bytes: bufferToBytes(Buffer.from(pdf, 'ascii')),
    mime: 'application/pdf'
  };
}
