use crate::providers::ModelInfo;
use crate::todo::TodoInput;
use crate::types::ApprovalRequest;

/// Origin of an approval request: the parent agent or a specific subagent.
///
/// The TUI tags queued approvals with this so concurrent parent/child requests
/// never collide in the approval queue — answering one pops only the matching
/// entry and immediately surfaces the next.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ApprovalSource {
    /// The parent chat agent (`task_id` matches the live turn).
    Parent,
    /// A subagent, identified by its stable id.
    Subagent { id: String },
}

/// An agent event tagged with the chat task that produced it.
///
/// Discovery tasks use `task_id = 0`; chat tasks use a monotonically
/// increasing id so the TUI can ignore events from stale/canceled tasks.
#[derive(Debug, Clone)]
pub struct AgentTaskEvent {
    pub task_id: u64,
    pub event: AgentEvent,
}

#[derive(Debug, Clone)]
pub enum AgentEvent {
    Thinking,
    TextDelta(String),
    ReasoningDelta(String),
    /// Cumulative generated bytes this turn, including reasoning and tool JSON.
    /// A display estimate only; never a substitute for provider billing usage.
    GenerationProgress {
        subagent_id: Option<String>,
        output_bytes: usize,
        tool_name: Option<String>,
    },
    AssistantText(String),
    ToolCallStart {
        id: String,
        name: String,
        args: String,
    },
    ToolCallProgress {
        id: String,
        chunk: String,
    },
    /// Liveness tick from a still-running tool (long shell command, waiting
    /// subagent). Carries no payload — it exists so the TUI's stuck guard can
    /// tell "working quietly" from "dead stream".
    ToolHeartbeat {
        id: String,
    },
    ToolCallResult {
        id: String,
        name: String,
        result: String,
        is_error: bool,
    },
    FileChange {
        /// `None` for the parent agent; `Some(id)` when a subagent produced
        /// it. Consumers must never attribute a child's checkout change to the
        /// parent workspace without checking this.
        subagent_id: Option<String>,
        path: String,
        diff_summary: String,
        before: Option<String>,
        after: Option<String>,
    },
    TodoUpdate {
        /// `None` for the parent agent; `Some(id)` for a subagent. A child's
        /// todo list is not the parent's plan.
        subagent_id: Option<String>,
        todos: Vec<TodoInput>,
    },
    Done {
        conversation: Vec<crate::types::Message>,
        tokens: u32,
    },
    Cancelled {
        conversation: Vec<crate::types::Message>,
        tokens: u32,
        partial_text: String,
    },
    /// Compaction is starting (smart = an LLM summary is being written,
    /// which can take a while). Followed by `ContextCompacted` on success.
    CompactionStarted {
        smart: bool,
    },
    ContextCompacted {
        summary: String,
        /// Estimated context before and after, for the transcript divider.
        tokens_before: u32,
        tokens_after: u32,
        /// Summarized by the model (smart) rather than trimmed.
        smart: bool,
        /// The compacted transcript. The TUI replaces `session.conversation`
        /// immediately so the status bar reflects the post-compact size
        /// before the turn finishes.
        compacted_conversation: Vec<crate::types::Message>,
    },
    /// Per-turn usage from the provider (prompt / completion / cache fields).
    /// The TUI consumes this for accurate cost accounting on the status bar.
    /// `conversation` is omitted — `Done`/`Cancelled` still carry the full
    /// transcript; this is informational only.
    TurnUsage {
        prompt_tokens: u32,
        completion_tokens: u32,
        cache_read_tokens: u32,
        cache_creation_tokens: u32,
    },
    /// One model call finished: its own token buckets and what it cost.
    /// Emitted per call by every loop — subagents included, forwarded up to
    /// the parent — so summing these gives the session's real spend.
    /// `cost_usd` is `None` when the catalog has no price for the model.
    CallUsage {
        prompt_tokens: u32,
        completion_tokens: u32,
        cache_read_tokens: u32,
        cache_creation_tokens: u32,
        cost_usd: Option<f64>,
        /// The subagent whose loop made the call (`None` = the main agent).
        /// Set by the forwarder; nested children keep their own id.
        subagent_id: Option<String>,
    },
    /// The provider request failed transiently (429/5xx/network) and the loop
    /// is backing off before retrying. The TUI surfaces this on the status bar.
    Retry {
        attempt: u32,
        max_attempts: u32,
        delay_ms: u64,
    },
    Error {
        message: String,
        /// The loop's transcript as of the failure, including any tool work
        /// the turn already executed. Empty when the failure happened before
        /// a transcript existed (panic), in which case the owner falls back
        /// to its last known conversation.
        conversation: Vec<crate::types::Message>,
    },
    ModelsDiscovered {
        provider: String,
        models: Vec<ModelInfo>,
    },
    ModelDiscoveryFailed {
        provider: String,
        error: String,
    },
    ModelCatalogUpdated {
        result: Result<crate::catalog::ModelCatalog, String>,
    },
    ApprovalRequested {
        /// Who asked for the approval (parent or a specific subagent). The TUI
        /// uses this to keep concurrent parent/child requests distinct.
        source: ApprovalSource,
        request: ApprovalRequest,
    },
    /// A subagent was spawned (background or foreground).
    SubagentStarted {
        id: String,
        subagent_type: String,
        description: String,
    },
    /// Live text streamed from a subagent.
    SubagentText {
        id: String,
        text: String,
    },
    /// A subagent started a tool call.
    SubagentToolCallStart {
        id: String,
        call_id: String,
        name: String,
        args: String,
    },
    /// Live output from a subagent tool call.
    SubagentToolCallProgress {
        id: String,
        call_id: String,
        chunk: String,
    },
    /// A subagent finished a tool call.
    SubagentToolCallResult {
        id: String,
        call_id: String,
        name: String,
        result: String,
        is_error: bool,
    },
    /// A subagent reached a terminal state (completed / failed / cancelled).
    SubagentDone {
        id: String,
        summary: String,
        is_error: bool,
    },
    /// A background subagent finished with no live waiter: model-facing
    /// completion notice (push, not poll). The TUI injects it into the
    /// parent conversation so the model learns the result without calling
    /// `task_output`. Never sent when a waiter already holds the result
    /// (foreground spawn, active `task_output` poll, or a previous
    /// terminal delivery).
    SubagentCompletedNotice {
        id: String,
        subagent_type: String,
        status: String,
        summary: String,
    },
}
